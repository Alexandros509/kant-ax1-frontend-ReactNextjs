-- 회원 전용 Todo 앱 - todos 테이블 + RLS 정책
-- Supabase 대시보드 > SQL Editor에 붙여 넣고 한 번 실행합니다.

-- 할 일 테이블 (교안 7장 2강 컬럼 + 7장 3강 user_id)
create table public.todos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  title text not null,
  is_completed boolean not null default false,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade
);

-- RLS(행 수준 보안) 활성화
alter table public.todos enable row level security;

-- 로그인한 사용자가 본인의 데이터만 조회·추가·수정·삭제하도록 허용
create policy "본인 할 일 조회"
on public.todos for select to authenticated
using (auth.uid() = user_id);

create policy "본인 할 일 생성"
on public.todos for insert to authenticated
with check (auth.uid() = user_id);

create policy "본인 할 일 수정"
on public.todos for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "본인 할 일 삭제"
on public.todos for delete to authenticated
using (auth.uid() = user_id);
